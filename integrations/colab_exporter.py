"""Google Colab Notebook Exporter using nbformat."""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
import nbformat as nbf
from config.settings import settings

logger = logging.getLogger(__name__)

class ColabExporter:
    """Generates valid Jupyter notebooks (.ipynb) customized for Google Colab execution."""

    def __init__(self, output_dir: Optional[Path] = None):
        self.output_dir = output_dir or settings.notebooks_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_notebook(
        self,
        experiment_name: str,
        problem_statement: str,
        dataset_meta: Dict[str, Any],
        preprocessing_config: Dict[str, Any],
        model_config: Dict[str, Any],
        experiment_id: str,
        version_number: int = 1
    ) -> Path:
        """Create a complete, syntactically valid .ipynb file adapted to the experiment."""
        nb = nbf.v4.new_notebook()
        cells = []

        # 1. Title & Problem Statement
        cells.append(nbf.v4.new_markdown_cell(
            f"# 🧪 Autonomous AI Lab Assistant: {experiment_name}\n\n"
            f"**Experiment ID:** `{experiment_id}` | **Version:** `v{version_number}`\n\n"
            f"### Problem Statement\n"
            f"> {problem_statement}\n\n"
            f"---\n"
            f"*This notebook was automatically generated by the Autonomous AI Lab Assistant for execution in Google Colab.*"
        ))

        # 2. Hardware and Environment Setup
        cells.append(nbf.v4.new_markdown_cell("## 1. Hardware Check & Dependencies Setup\nCheck GPU accelerator availability and install required packages."))
        cells.append(nbf.v4.new_code_cell(
            "# Check hardware accelerator\n"
            "import os\n"
            "import sys\n"
            "import torch\n\n"
            "device = 'cuda' if torch.cuda.is_available() else 'cpu'\n"
            "print(f'Execution Device: {device}')\n"
            "if device == 'cuda':\n"
            "    print(f'GPU Device Name: {torch.cuda.get_device_name(0)}')\n\n"
            "# Install required dependencies\n"
            "!pip install --quiet scikit-learn pandas numpy matplotlib seaborn plotly\n"
            "print('Environment setup complete.')"
        ))

        # 3. Experiment Configuration
        config_summary = {
            "experiment_id": experiment_id,
            "version": version_number,
            "dataset": dataset_meta.get("name", "Custom Dataset"),
            "target_column": dataset_meta.get("target_column", "target"),
            "task_type": dataset_meta.get("task_type", "classification"),
            "model": model_config.get("model_name", "RandomForestClassifier"),
            "framework": model_config.get("framework", "scikit-learn"),
            "hyperparameters": model_config.get("hyperparameters", {}),
            "preprocessing": preprocessing_config
        }
        cells.append(nbf.v4.new_markdown_cell("## 2. Experiment Configuration\nFormal parameters registered for this run."))
        cells.append(nbf.v4.new_code_cell(
            f"CONFIG = {json.dumps(config_summary, indent=4)}\n"
            "print('Loaded Experiment Configuration:')\n"
            "for k, v in CONFIG.items():\n"
            "    print(f'  {k}: {v}')"
        ))

        # 4. Dataset Loading & Validation
        task_type = dataset_meta.get("task_type", "classification")
        dataset_name = dataset_meta.get("name", "dataset")
        target_col = dataset_meta.get("target_column", "target")

        cells.append(nbf.v4.new_markdown_cell("## 3. Dataset Ingestion\nDownload or load the verified dataset into pandas."))
        
        # Adaptive loading logic
        if "iris" in dataset_name.lower():
            load_code = (
                "from sklearn.datasets import load_iris\n"
                "import pandas as pd\n\n"
                "raw = load_iris(as_frame=True)\n"
                "df = raw.frame\n"
                f"print('Dataset shape:', df.shape)\n"
                "df.head()"
            )
        elif "wine" in dataset_name.lower():
            load_code = (
                "from sklearn.datasets import load_wine\n"
                "import pandas as pd\n\n"
                "raw = load_wine(as_frame=True)\n"
                "df = raw.frame\n"
                f"print('Dataset shape:', df.shape)\n"
                "df.head()"
            )
        elif "breast_cancer" in dataset_name.lower() or "cancer" in dataset_name.lower():
            load_code = (
                "from sklearn.datasets import load_breast_cancer\n"
                "import pandas as pd\n\n"
                "raw = load_breast_cancer(as_frame=True)\n"
                "df = raw.frame\n"
                f"print('Dataset shape:', df.shape)\n"
                "df.head()"
            )
        elif "housing" in dataset_name.lower():
            load_code = (
                "from sklearn.datasets import fetch_california_housing\n"
                "import pandas as pd\n\n"
                "raw = fetch_california_housing(as_frame=True)\n"
                "df = raw.frame\n"
                f"print('Dataset shape:', df.shape)\n"
                "df.head()"
            )
        elif "diabetes" in dataset_name.lower():
            load_code = (
                "from sklearn.datasets import load_diabetes\n"
                "import pandas as pd\n\n"
                "raw = load_diabetes(as_frame=True)\n"
                "df = raw.frame\n"
                f"print('Dataset shape:', df.shape)\n"
                "df.head()"
            )
        else:
            load_code = (
                "import pandas as pd\n"
                "# In Colab, you can upload your CSV file or download it from a URL:\n"
                "# from google.colab import files\n"
                "# uploaded = files.upload()\n"
                "# df = pd.read_csv(list(uploaded.keys())[0])\n\n"
                "# Alternatively, load from OpenML / public URL:\n"
                "print('Please provide your dataset path or upload file:')\n"
                "# df = pd.read_csv('your_dataset.csv')\n"
                "from sklearn.datasets import make_classification\n"
                "X_sim, y_sim = make_classification(n_samples=500, n_features=10, random_state=42)\n"
                "df = pd.DataFrame(X_sim, columns=[f'feat_{i}' for i in range(10)])\n"
                f"df['{target_col}'] = y_sim\n"
                "print('Loaded dataset with shape:', df.shape)\n"
                "df.head()"
            )

        cells.append(nbf.v4.new_code_cell(load_code))

        # 5. Exploratory Data Analysis & Leakage Check
        cells.append(nbf.v4.new_markdown_cell("## 4. Exploratory Data Analysis\nInspect data types, missing values, and target distribution."))
        cells.append(nbf.v4.new_code_cell(
            "print('Missing Values Count:')\n"
            "print(df.isnull().sum())\n\n"
            "print('\\nData Types:')\n"
            "print(df.dtypes)\n\n"
            f"if '{target_col}' in df.columns:\n"
            f"    print('\\nTarget Distribution:')\n"
            f"    print(df['{target_col}'].value_counts())\n"
            "else:\n"
            f"    print('Warning: Target column {target_col} not found in dataframe.')"
        ))

        # 6. Preprocessing & Data Splitting
        test_size = preprocessing_config.get("test_size", 0.2)
        random_state = preprocessing_config.get("random_state", 42)
        scale_numeric = preprocessing_config.get("scale_numeric", "standard")

        cells.append(nbf.v4.new_markdown_cell("## 5. Preprocessing & Train/Validation/Test Split\nApply leakage-free transformations fit strictly on training splits."))
        cells.append(nbf.v4.new_code_cell(
            "from sklearn.model_selection import train_test_split\n"
            "from sklearn.preprocessing import StandardScaler, MinMaxScaler\n"
            "import numpy as np\n\n"
            f"target = '{target_col}' if '{target_col}' in df.columns else df.columns[-1]\n"
            "X = df.drop(columns=[target])\n"
            "y = df[target]\n\n"
            "# Retain only numeric features for baseline modeling\n"
            "X = X.select_dtypes(include=[np.number])\n"
            "X = X.fillna(X.median())\n\n"
            f"X_train, X_test, y_train, y_test = train_test_split(X, y, test_size={test_size}, random_state={random_state})\n"
            "print(f'Train samples: {len(X_train)}, Test samples: {len(X_test)}')\n\n"
            + ("scaler = StandardScaler()\n"
               "X_train_scaled = scaler.fit_transform(X_train)\n"
               "X_test_scaled = scaler.transform(X_test)\n"
               "print('Applied StandardScaler on features.')"
               if scale_numeric == "standard" else
               "X_train_scaled = X_train.values\nX_test_scaled = X_test.values\nprint('Raw numeric features retained.')")
        ))

        # 7. Model Definition & Training
        model_name = model_config.get("model_name", "RandomForestClassifier")
        cells.append(nbf.v4.new_markdown_cell("## 6. Model Training\nInitialize candidate architecture and fit on the training set."))
        
        if "regression" in task_type.lower():
            train_code = (
                "import time\n"
                "from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor\n"
                "from sklearn.linear_model import Ridge\n\n"
                "start_time = time.time()\n"
                "model = RandomForestRegressor(n_estimators=100, random_state=42)\n"
                "model.fit(X_train_scaled, y_train)\n"
                "duration = time.time() - start_time\n"
                "print(f'Model training completed in {duration:.3f} seconds.')"
            )
        else:
            train_code = (
                "import time\n"
                "from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier\n"
                "from sklearn.linear_model import LogisticRegression\n\n"
                "start_time = time.time()\n"
                "model = RandomForestClassifier(n_estimators=100, random_state=42)\n"
                "model.fit(X_train_scaled, y_train)\n"
                "duration = time.time() - start_time\n"
                "print(f'Model training completed in {duration:.3f} seconds.')"
            )
        cells.append(nbf.v4.new_code_cell(train_code))

        # 8. Evaluation & Visualizations
        cells.append(nbf.v4.new_markdown_cell("## 7. Model Evaluation\nCalculate unbiased test performance metrics."))
        if "regression" in task_type.lower():
            eval_code = (
                "from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score\n"
                "import matplotlib.pyplot as plt\n\n"
                "y_pred = model.predict(X_test_scaled)\n"
                "mse = mean_squared_error(y_test, y_pred)\n"
                "rmse = np.sqrt(mse)\n"
                "mae = mean_absolute_error(y_test, y_pred)\n"
                "r2 = r2_score(y_test, y_pred)\n\n"
                "print(f'MAE:  {mae:.4f}')\n"
                "print(f'RMSE: {rmse:.4f}')\n"
                "print(f'R2:   {r2:.4f}')\n\n"
                "plt.figure(figsize=(7, 5))\n"
                "plt.scatter(y_test, y_pred, alpha=0.7)\n"
                "plt.plot([y_test.min(), y_test.max()], [y_test.min(), y_test.max()], 'r--')\n"
                "plt.xlabel('Actual')\n"
                "plt.ylabel('Predicted')\n"
                "plt.title('Actual vs Predicted')\n"
                "plt.show()"
            )
        else:
            eval_code = (
                "from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix, classification_report\n"
                "import seaborn as sns\n"
                "import matplotlib.pyplot as plt\n\n"
                "y_pred = model.predict(X_test_scaled)\n"
                "acc = accuracy_score(y_test, y_pred)\n"
                "prec = precision_score(y_test, y_pred, average='weighted', zero_division=0)\n"
                "rec = recall_score(y_test, y_pred, average='weighted', zero_division=0)\n"
                "f1 = f1_score(y_test, y_pred, average='weighted', zero_division=0)\n\n"
                "print(f'Accuracy:  {acc:.4f}')\n"
                "print(f'Precision: {prec:.4f}')\n"
                "print(f'Recall:    {rec:.4f}')\n"
                "print(f'F1-Score:  {f1:.4f}')\n"
                "print('\\nClassification Report:\\n', classification_report(y_test, y_pred, zero_division=0))\n\n"
                "cm = confusion_matrix(y_test, y_pred)\n"
                "plt.figure(figsize=(6, 5))\n"
                "sns.heatmap(cm, annot=True, fmt='d', cmap='Blues')\n"
                "plt.title('Confusion Matrix')\n"
                "plt.xlabel('Predicted')\n"
                "plt.ylabel('True')\n"
                "plt.show()"
            )
        cells.append(nbf.v4.new_code_cell(eval_code))

        # 9. Artifact & Colab Export Results JSON
        cells.append(nbf.v4.new_markdown_cell(
            "## 8. Export Results Package\n"
            "This block exports an `experiment_results.json` file that you can import back into the **Autonomous AI Lab Assistant** web dashboard."
        ))
        export_script = (
            "import json\n"
            "results_payload = {\n"
            f"    'experiment_id': '{experiment_id}',\n"
            f"    'version_number': {version_number},\n"
            "    'status': 'completed',\n"
            "    'execution_mode': 'colab',\n"
            "    'metrics': {\n"
            "        'primary_metric': 'r2' if '" + task_type + "' == 'regression' else 'accuracy',\n"
            "        'primary_value': float(r2) if '" + task_type + "' == 'regression' else float(acc),\n"
            "        'metrics_dict': {\n"
            "            'accuracy': float(acc) if '" + task_type + "' != 'regression' else 0.0,\n"
            "            'f1_score': float(f1) if '" + task_type + "' != 'regression' else 0.0,\n"
            "            'rmse': float(rmse) if '" + task_type + "' == 'regression' else 0.0,\n"
            "            'mae': float(mae) if '" + task_type + "' == 'regression' else 0.0\n"
            "        }\n"
            "    },\n"
            "    'duration_seconds': duration\n"
            "}\n\n"
            "with open('experiment_results.json', 'w') as f:\n"
            "    json.dump(results_payload, f, indent=4)\n"
            "print('Results successfully serialized to experiment_results.json! You can download this file and import it into the Lab Assistant.')"
        )
        cells.append(nbf.v4.new_code_cell(export_script))

        nb["cells"] = cells

        # Safe filename
        safe_name = "".join(c for c in experiment_name if c.isalnum() or c in (" ", "_", "-")).rstrip()
        filename = f"{safe_name.replace(' ', '_')}_v{version_number}.ipynb"
        file_path = self.output_dir / filename

        with open(file_path, "w", encoding="utf-8") as f:
            nbf.write(nb, f)

        logger.info(f"Generated Colab notebook: {file_path}")
        return file_path
